"""PDF version of the CV report (reportlab)."""
import io

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

GREEN = colors.HexColor("#4B2FD6")
LIME = colors.HexColor("#FFC23D")
RED = colors.HexColor("#E5484D")
PRIO = {"critical": RED, "high": colors.HexColor("#E8692E"), "medium": colors.HexColor("#C99A06"), "low": colors.grey}


def build_cv_report_pdf(analysis) -> bytes:
    r = analysis.report
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm, bottomMargin=16 * mm,
                            title="Sonarhorin CV Report")
    ss = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=ss["Title"], alignment=0, fontSize=22, textColor=colors.black, spaceAfter=2)
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], textColor=GREEN, spaceBefore=10, spaceAfter=4)
    body = ParagraphStyle("b", parent=ss["BodyText"], fontSize=9.5, leading=13)
    small = ParagraphStyle("s", parent=body, fontSize=8.5, textColor=colors.grey)
    el = []
    el.append(Paragraph("Sonarhorin<font color='#E8B634'>.</font> CV Report", h1))
    el.append(Paragraph(f"{analysis.user.full_name} · {analysis.original_name} · {analysis.created_at:%d %b %Y}", small))
    el.append(Spacer(1, 8))

    summary = Table(
        [["CV score", "Rejection risk", "Verdict"],
         [f"{r['score']}/100", f"{r['rejection_probability']}%", r["verdict"]]],
        colWidths=[55 * mm, 55 * mm, 64 * mm],
    )
    summary.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), GREEN), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTSIZE", (0, 1), (-1, 1), 16), ("FONTNAME", (0, 1), (-1, 1), "Helvetica-Bold"),
        ("TEXTCOLOR", (1, 1), (1, 1), RED if r["rejection_probability"] >= 50 else GREEN),
        ("BOX", (0, 0), (-1, -1), 0.6, colors.black), ("INNERGRID", (0, 0), (-1, -1), 0.3, colors.lightgrey),
        ("TOPPADDING", (0, 0), (-1, -1), 6), ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    el.append(summary)

    el.append(Paragraph("Score breakdown", h2))
    rows = [["Area", "Points"]] + [[b["name"], f"{b['earned']} / {b['possible']}"] for b in r["breakdown"]]
    t = Table(rows, colWidths=[120 * mm, 54 * mm])
    t.setStyle(TableStyle([("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"), ("LINEBELOW", (0, 0), (-1, -1), 0.3, colors.lightgrey)]))
    el.append(t)

    el.append(Paragraph("What's already strong", h2))
    for s in r["strengths"] or ["Nothing stood out yet — the fixes below will change that."]:
        el.append(Paragraph(f"+ {s}", body))

    el.append(Paragraph("What to fix (most important first)", h2))
    for f in r["improvements"]:
        c = PRIO.get(f["priority"], colors.grey).hexval()[2:]
        el.append(Paragraph(f"<font color='#{c}'><b>[{f['priority'].upper()}]</b></font> <b>{f['section']}: {f['title']}</b>", body))
        el.append(Paragraph(f["tip"], body))
        if f.get("example"):
            el.append(Paragraph(f"<i>Example: {f['example']}</i>", small))
        el.append(Spacer(1, 4))

    if r.get("ai_suggestions"):
        el.append(Paragraph("Line-by-line rewrites (AI)", h2))
        for s in r["ai_suggestions"]:
            el.append(Paragraph(f"<b>Before:</b> {s.get('before','')}", body))
            el.append(Paragraph(f"<b>After:</b> {s.get('after','')}", body))
            el.append(Paragraph(f"<i>{s.get('why','')}</i>", small))
            el.append(Spacer(1, 4))

    el.append(Paragraph("Recommended section order", h2))
    for i, s in enumerate(r["recommended_order"], 1):
        el.append(Paragraph(f"{i}. {s}", body))

    kw = r.get("keywords", {})
    if kw.get("missing"):
        el.append(Paragraph("Keywords recruiters search for (that you could add, if true)", h2))
        el.append(Paragraph(", ".join(kw["missing"]), body))

    el.append(Spacer(1, 12))
    el.append(Paragraph("Generated by Sonarhorin (সোনারহরিণ) · Rejection risk is an estimate from CV-screening rules, not a guarantee.", small))
    doc.build(el)
    return buf.getvalue()
